"""The PIXL factory library: 128 presets (SPEC §9).

Numbering: Lead 001-032, Bass 033-056, Arp 057-074, Pad 075-086, Drum 087-108, SFX 109-128.
The twelve presets of the design (docs/design/source/PIXL.dc.html, `PR` in renderVals) keep
their names, chips, icons and Russian descriptions verbatim; 014 "Hyrule Fanfare" is the init
state (stored as `params: {}`, default wave, factory-default macros).

Read dsl.py first: stored values are what each target does with its macro at 0 %, and every
macro routing is written as (parameter, value at 100 %). Macro roles are consistent across
the library:

  BRIGHT  duty narrowing, octave/fifth layers, noise brightness, attack snap, sweep "zap"
  DIRT    the bitcrusher (wired transparent at 16 bit / 48 kHz), detune, noise grit
  MOTION  vibrato, glide, arp speed/range, sweep and envelope movement
  SPACE   SNES-style echo, unison width, stereo spread, release tails

BRIGHT, MOTION and SPACE load at 62/45/20 % unless a preset says otherwise; descriptions
describe the sound at those positions. DIRT is stored at 0 % (dsl.Preset rebases whatever is
written here), so every preset loads clean and DIRT adds the grit. Further conventions:

  - one-shots (sustain 0) release about as long as they decay (half of it for the NES
    triangle, whose envelope only gates), so short MIDI notes do not choke the hit;
  - detuned layers are detuned symmetrically around the note;
  - GB unison width only matters below 33 % (hard L/C/R panning), so GB presets give SPACE
    to the echo and the release instead;
  - NES/GB pulses cannot play below ≈ 55 / 64 Hz: GB sub-octaves go on the wave channel.
  - `analog` (the chip's unipolar DAC + output filter) stays on unless it costs the sound: NES
    basses and kicks turn it off to keep the fundamental the 2A03's 90/440 Hz high-pass
    removes; elsewhere it goes off where the DAC's note-on step (the unipolar "pop") would eat
    several dB of headroom or thump under a staccato bass, a hat or a dense arp.
"""

